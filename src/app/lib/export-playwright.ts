import type { TestSuite } from "@/src/app/types/testmind";

const q = (s: string) => JSON.stringify(s);

/**
 * Turns a suite into a Playwright spec skeleton: one test per case, steps as
 * test.step blocks, expected result as a comment, and test.fixme so the file
 * runs green-but-pending until someone wires up the selectors.
 */
export function toPlaywrightSpec(suite: TestSuite): string {
  const lines: string[] = [
    `// Generated by TestMind from suite ${suite.id}`,
    `// Feature: ${suite.featureName}`,
    `import { test, expect } from "@playwright/test";`,
    ``,
    `test.describe(${q(suite.featureName)}, () => {`,
  ];

  for (const tc of suite.testCases) {
    const type = String(tc.type || "").toLowerCase();
    lines.push(`  test(${q(`${tc.id} [${type}] ${tc.title}`)}, { tag: ${q(`@${type}`)} }, async ({ page }) => {`);
    lines.push(`    test.fixme(true, "Generated skeleton: implement steps and assertions");`);
    tc.steps.forEach((step, i) => {
      lines.push(`    await test.step(${q(`${i + 1}. ${step}`)}, async () => {`, `      // TODO`, `    });`);
    });
    lines.push(`    // Expected: ${tc.expected.replace(/\n/g, " ")}`);
    if (tc.samplePayload && Object.keys(tc.samplePayload).length) {
      lines.push(`    const payload = ${JSON.stringify(tc.samplePayload)};`, `    void payload;`);
    }
    lines.push(`    await expect(page).toBeTruthy();`, `  });`, ``);
  }

  lines.push(`});`, ``);
  return lines.join("\n");
}

export function download(filename: string, content: string, type: string) {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "suite";
